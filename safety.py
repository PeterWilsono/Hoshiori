# -*- coding: utf-8 -*-
"""本地风险识别：不依赖模型自觉，也不额外花钱。

设计原则：

- **不做审查**。命中不等于拦截，只是把提示词切到"认真一点"的档位——她说的话
  还是她说的，只是不再开玩笑、不再用"抱抱"糊过去。
- **规则要窄**。宁可漏一点，也不能把"烦死了""困死了"当成自伤。所以只认
  明确的、指向自己的表述，而且要求上下文里没有明确的玩笑/转述标记。
- **只读文本**。不写库、不联网、不调模型，纯字符串匹配，微秒级。

识别结果分两档：
  ``concern``  情绪很重、可能正在崩溃（"撑不住了""活着好累"）
  ``risk``     明确的自我伤害表述（"不想活了""想死"）
"""
import re

__all__ = ["check", "SAFETY_NOTE", "CRISIS_NOTE"]

#: 明确指向"不想活"的说法。这些词单独出现就足够触发。
_RISK = (
    "自杀", "自残", "割腕", "跳楼", "跳下去", "不想活", "不想活了", "不想醒来",
    "活着没意思", "活着没意义", "活着好累", "想死", "去死", "死了算了",
    "结束自己", "了结自己", "消失掉算了", "不如死了",
)

#: 情绪已经很重、但还没到明确自伤。给一个"轻一点"的提醒就够。
_CONCERN = (
    "撑不住", "扛不住", "受不了了", "崩溃", "熬不下去", "没有意义",
    "一片空白", "麻木", "喘不过气", "绝望", "没人在乎", "没人需要我",
)

#: 出现这些词时，上面那两类多半是转述或玩笑（"电影里那人想死"）。
_QUOTED = ("他说", "她说", "他说他", "电影", "小说", "剧里", "歌里", "台词",
           "开玩笑", "哈哈", "笑死", "打游戏")

_negation = re.compile(r"(不|没|别)想死|不想死")

#: 这些是口语里的夸张或骂人，语义上跟自我伤害无关，先剔掉再判
_INNOCENT = re.compile(r"想死你|想死您|去死吧|你死|他死|她死|死我了|笑死|累死|困死")


def check(text):
    """返回 (level, note)。level ∈ 0 / 'concern' / 'risk'，note 是可直接拼进提示词的话。"""
    t = (text or "").strip()
    if not t or len(t) > 400:
        return 0, ""
    t = _INNOCENT.sub("", t)

    if any(q in t for q in _QUOTED):
        # 转述/玩笑场景：不升级，但"自杀"这种字眼还是给一句轻提醒
        if any(w in t for w in ("自杀", "想死", "不想活")):
            return "concern", CRISIS_NOTE
        return 0, ""

    if _negation.search(t):
        return "concern", CONCERN_NOTE

    if any(w in t for w in _RISK):
        return "risk", SAFETY_NOTE
    if any(w in t for w in _CONCERN):
        return "concern", CONCERN_NOTE
    return 0, ""


SAFETY_NOTE = (
    "【这一轮认真一点】"
    "他说的话里可能有伤害自己的意思。先别接梗、别讲道理、别用「想开点」这种话。"
    "用你自己的语气让他知道你在，问他现在人在哪儿、身边有没有人。"
    "不要说教，不要承诺你做不到的事，也不要突然变成客服。"
)

CRISIS_NOTE = (
    "【这一轮轻一点】"
    "他的情绪很重。少说话，别分析，别给方案。一句「我在」比十句建议有用。"
)

CONCERN_NOTE = (
    "【这一轮慢一点】"
    "他状态不太好。别急着逗他开心，也别急着问为什么。先陪着。"
)
